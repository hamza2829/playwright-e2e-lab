import fs from 'node:fs/promises';
import path from 'node:path';
import type { DraftAdapter } from './adapters/types.ts';
import { buildPrompt, FIXTURES_PLACEHOLDER } from './prompt.ts';
import type { Story } from './story.ts';

export const REPO_ROOT = path.resolve(import.meta.dirname, '..', '..');
export const FIXTURES_FILE = path.join(REPO_ROOT, 'tests', 'web', 'fixtures.ts');

/** Pulls the first ```ts block out of a model response (or returns the text as-is). */
export function extractCode(response: string): string {
  const m = /```(?:ts|typescript|js|javascript)?\s*\n([\s\S]*?)```/.exec(response);
  return (m ? m[1] : response).trim();
}

/** Points every fixtures import at the real file, relative to where the draft is written. */
export function fixImports(code: string, outDir: string): string {
  let rel = path.relative(outDir, FIXTURES_FILE).split(path.sep).join('/');
  if (!rel.startsWith('.')) rel = `./${rel}`;
  return code.replace(
    new RegExp(`from\\s+['"](${FIXTURES_PLACEHOLDER.replace('@', '@?')}|[^'"]*fixtures(?:\\.ts)?)['"]`, 'g'),
    `from '${rel}'`,
  );
}

export function header(story: Story, adapter: DraftAdapter): string {
  return [
    `// DRAFT generated by the genai helper (adapter: ${adapter.name}) from genai/stories/${story.file}.`,
    '// Not reviewed. Check it against genai/REVIEW_CHECKLIST.md before moving it into tests/web/generated/.',
  ].join('\n');
}

export interface DraftOutcome {
  slug: string;
  file: string;
  ms: number;
  error?: string;
}

export async function draftAll(stories: Story[], adapter: DraftAdapter, outDir: string, savePrompts = false): Promise<DraftOutcome[]> {
  await fs.mkdir(outDir, { recursive: true });
  const outcomes: DraftOutcome[] = [];
  for (const story of stories) {
    const file = path.join(outDir, `${story.slug}.spec.ts`);
    const prompt = buildPrompt(story);
    if (savePrompts) await fs.writeFile(path.join(outDir, `${story.slug}.prompt.txt`), prompt, 'utf8');
    const started = Date.now();
    try {
      const response = await adapter.generate({ story, prompt });
      const code = fixImports(extractCode(response), outDir);
      await fs.writeFile(file, `${header(story, adapter)}\n${code}\n`, 'utf8');
      outcomes.push({ slug: story.slug, file, ms: Date.now() - started });
    } catch (err) {
      const message = err instanceof Error ? err.message : String(err);
      await fs.writeFile(file, `${header(story, adapter)}\n// Generation failed: ${message}\n`, 'utf8');
      outcomes.push({ slug: story.slug, file, ms: Date.now() - started, error: message });
    }
  }
  return outcomes;
}
